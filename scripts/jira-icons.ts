// Writes src/card-templates/icons.ts from the PNG files in src/assets/jira-icons.
// Run it after you change an icon: bun scripts/jira-icons.ts
// test/card-templates.test.ts fails when the two are out of step.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const dir = join(root, "src", "assets", "jira-icons");
const names = readdirSync(dir).filter(name => name.endsWith(".png")).sort();
const lines = names.map(name => `  ${JSON.stringify(name.slice(0, -4))}: ${JSON.stringify(`data:image/png;base64,${readFileSync(join(dir, name)).toString("base64")}`)},`);
const source = `// Generated by scripts/jira-icons.ts from src/assets/jira-icons/*.png. Do not edit by hand.
// Jira issue type icons, 32 px, as PNG data URIs. Teams shows a PNG data URI in a card. It does not show SVG.
export const JIRA_ICONS: Record<string, string> = {
${lines.join("\n")}
};
`;
writeFileSync(join(root, "src", "card-templates", "icons.ts"), source);
console.log(`Wrote ${names.length} icons.`);
