// Writes the README command table from src/spec.ts. Run: bun run docs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readmeTable } from "../src/help.ts";

export const START = "<!-- commands:start (generated by `bun run docs` from src/spec.ts; do not edit) -->";
export const END = "<!-- commands:end -->";

export function withTable(readme: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error("README.md has no command table markers.");
  return `${readme.slice(0, start + START.length)}\n${readmeTable()}\n${readme.slice(end)}`;
}

if (import.meta.main) {
  const path = join(import.meta.dir, "..", "README.md");
  writeFileSync(path, withTable(readFileSync(path, "utf8")));
  console.log("README.md command table written.");
}
